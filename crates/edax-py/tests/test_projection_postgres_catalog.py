"""Projection catalog admission matches the columns its fixed inserts can write."""

from __future__ import annotations

import os
from collections.abc import AsyncIterator
from typing import Any
from uuid import uuid4

import pytest
from edax.backend.postgres import PostgresTransactor
from edax.backend.projection_postgres import PostgresProjectionStateStore, reference_projection_state_ddl
from edax.errors import BadHandle
from edax.projection import ProjectionEvent, ProjectionInput, ProjectionResult
from test_projection_state import event, initial_cutover, proof, reducer, target


@pytest.fixture
async def database() -> AsyncIterator[tuple[Any, str]]:
    url = os.environ.get("EDAX_POSTGRES_URL")
    if url is None:
        if os.environ.get("EDAX_REQUIRE_POSTGRES") == "1":
            pytest.fail("EDAX_POSTGRES_URL required")
        pytest.skip("EDAX_POSTGRES_URL not set")
    import asyncpg

    pool = await asyncpg.create_pool(url, min_size=1, max_size=3)
    schema = f"projection_catalog_{uuid4().hex}"
    await pool.execute(f'CREATE SCHEMA "{schema}"')
    try:
        yield pool, schema
    finally:
        await pool.execute(f'DROP SCHEMA "{schema}" CASCADE')
        await pool.close()


@pytest.mark.parametrize(
    "original,replacement,extra,compatible",
    [
        pytest.param("", "", "", True, id="reference"),
        pytest.param("", "", "mandatory text NOT NULL", False, id="extra-required"),
        pytest.param("", "", "optional text", True, id="extra-nullable"),
        pytest.param("", "", "defaulted text NOT NULL DEFAULT 'audit'", True, id="extra-default"),
        pytest.param("", "", "identity_id bigint GENERATED ALWAYS AS IDENTITY", True, id="extra-identity"),
        pytest.param(
            "",
            "",
            "derived text GENERATED ALWAYS AS ('audit'::text) STORED NOT NULL",
            True,
            id="extra-generated",
        ),
        *[
            pytest.param(original, replacement, "", False, id=f"generated-{name}")
            for name, original, replacement in [
                (
                    "key",
                    'key text COLLATE "C" PRIMARY KEY',
                    "key text COLLATE \"C\" GENERATED ALWAYS AS ('fixed'::text) STORED PRIMARY KEY",
                ),
                (
                    "generation",
                    "generation text NOT NULL",
                    "generation text GENERATED ALWAYS AS ('balance-v1'::text) STORED NOT NULL",
                ),
                (
                    "source-partition",
                    "source_partition integer NOT NULL",
                    "source_partition integer GENERATED ALWAYS AS (0) STORED NOT NULL",
                ),
                (
                    "source-offset",
                    "source_offset bigint NOT NULL",
                    "source_offset bigint GENERATED ALWAYS AS (0) STORED NOT NULL",
                ),
                (
                    "ordinal",
                    "ordinal integer NOT NULL",
                    "ordinal integer GENERATED ALWAYS AS (0) STORED NOT NULL",
                ),
                (
                    "value",
                    "value jsonb NOT NULL",
                    "value jsonb GENERATED ALWAYS AS ('{}'::jsonb) STORED NOT NULL",
                ),
            ]
        ],
        *[
            pytest.param(
                f"{name} {kind} NOT NULL",
                f"{name} {kind} GENERATED ALWAYS AS IDENTITY",
                "",
                False,
                id=f"always-identity-{name}",
            )
            for name, kind in [
                ("source_partition", "integer"),
                ("source_offset", "bigint"),
                ("ordinal", "integer"),
            ]
        ],
        pytest.param(
            "ordinal integer NOT NULL",
            "ordinal integer GENERATED BY DEFAULT AS IDENTITY",
            "",
            True,
            id="inserted-default-identity",
        ),
    ],
)
async def test_projection_catalog_accepts_only_writable_intent_tables(
    database: tuple[Any, str], original: str, replacement: str, extra: str, compatible: bool
) -> None:
    pool, schema = database
    state_ddl, intent_ddl = reference_projection_state_ddl(schema).split(";\n", 1)
    if original:
        assert original in intent_ddl
        intent_ddl = intent_ddl.replace(original, replacement, 1)
    await pool.execute(state_ddl + ";\n" + intent_ddl)
    if extra:
        await pool.execute(f'ALTER TABLE "{schema}".edax_projection_intents ADD COLUMN {extra}')
    store = PostgresProjectionStateStore(PostgresTransactor(pool, schema=schema), target(), schema=schema)
    calls = 0

    def reduce(state: Any, incoming: ProjectionEvent) -> ProjectionResult:
        nonlocal calls
        calls += 1
        return reducer(state, incoming)

    assert await pool.fetchval(store._sql["check"]) is compatible
    if not compatible:
        with pytest.raises(BadHandle, match="tables do not meet the kernel contract"):
            await store.initialize()
        assert calls == 0
        assert await pool.fetchval(f'SELECT count(*) FROM "{schema}".edax_projection_state') == 0
        assert await pool.fetchval(f'SELECT count(*) FROM "{schema}".edax_projection_intents') == 0
        return
    await store.initialize()
    await store.activate(initial_cutover(store.target))
    lease = await store.acquire(0, "catalog-test", proof())
    updated = await store.commit(lease, [ProjectionInput(0, event())], proof(), reduce)
    assert calls == 1 and updated.next_offset == 1
    assert (await store.recover(updated)).next_offset == 1
    saved = await store.get("bank-eu", "account-42")
    assert saved is not None and saved["public"] == {"balance_minor": 1250, "currency": "EUR"}
    assert len(await store.unpublished(100)) == 1
    # Replaying the same event at a new source offset uses its durable receipt.
    await store.commit(updated, [ProjectionInput(1, event())], proof(), reduce)
    assert calls == 1
